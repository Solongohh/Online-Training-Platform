    console.log('Contact form submission:', {
      name,
      email: email.substring(0, 3) + '***', // Log partially for security
      phone: phone.substring(0, 3) + '***',
      subject,
      messageLength: message.length
    });

    // In a production environment, you would send an email here using Resend:
